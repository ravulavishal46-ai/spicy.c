export function getDish(idOrSlug: string) {
  return dishes.find((d) => d.id === idOrSlug || d.slug === idOrSlug);
}

export function getCategory(slug: string) {
  return categories.find((c) => c.slug === slug);
}

export function dishesInCategory(slug: string) {
  return dishes.filter((d) => d.category === slug);
}

export function comboCandidates(role: "main" | "side" | "drink") {
  const slugs = categories.filter((c) => c.comboRole === role).map((c) => c.slug);
  return dishes.filter((d) => slugs.includes(d.category));
}
